/** Its minute hand's eight places, clockwise from twelve: how far it reaches. */
const MINUTE_HAND = [
  [0, -1, 4],
  [1, -1, 3],
  [1, 0, 4],
  [1, 1, 3],
  [0, 1, 4],
  [-1, 1, 3],
  [-1, 0, 4],
  [-1, -1, 3],
] as const;

/**
 * The classic Macintosh's watch, the system busy at something: eight frames,
 * the minute hand going round past a short hour hand, about half past ten.
 */
export const WATCH: readonly Bitmap[] = MINUTE_HAND.map(([dx, dy, reach]) => {
  const rows = WATCH_CASE.map((row) => [...row]);
  const ink = (x: number, y: number) => {
    const row = rows[y];
    if (row) row[x] = '#';
  };
  const [x, y] = [7, 8];
  ink(x, y);
  ink(x - 1, y - 1);
  ink(x - 2, y - 2);
  for (let step = 1; step <= reach; step++) ink(x + dx * step, y + dy * step);
  return rows.map((row) => row.join(''));
});

/** The watch at a tick of the movies' clock: its hand goes round in two seconds. */
export const watchAt = (tick: number): Bitmap =>
  WATCH[Math.floor(tick / 2) % WATCH.length] ?? [];

